#!/usr/bin/env python3
import argparse
import sys

import pandas as pd

def parse_args():
    parser = argparse.ArgumentParser(
        description="Select the best reference genome from a quantification TSV."
    )
    parser.add_argument("-i", "--input", type=str, required=True, help="Path to the input TSV file")
    parser.add_argument("-s", "--sample_name", type=str, required=True, help="Sample name")
    parser.add_argument("--top", type=float, required=True, help="Top percent of TPM to select target_ids within")
    parser.add_argument(
        "-b",
        "--best_ref_txt",
        required=True,
        type=str,
        default="best_reference.txt",
        help="Output TXT file path containing the best reference ID",
    )
    parser.add_argument(
        "-a",
        "--alternate_subtype_txt",
        required=True,
        type=str,
        default="alternate_subtypes.txt",
        help="Output TXT file path containing alternate reference IDs",
    )
    parser.add_argument("--salmon", action="store_true", help="Input was generated by salmon rather than kallisto")
    parser.add_argument("-o", "--output", type=str, default="best_reference.tsv", help="Output TSV file path")
    parser.add_argument(
        "-t",
        "--tpm_threshold",
        type=float,
        default=250000,
        help="Minimum TPM threshold used to flag other potential subtypes",
    )
    return parser.parse_args()

def require_columns(df, columns):
    missing = [column for column in columns if column not in df.columns]
    if missing:
        raise ValueError(f"Input TSV is missing required columns: {', '.join(missing)}")

def process_data(input_path, salmon, sample_name, top_percent, best_ref_txt, alternate_subtype_txt, output_path, tpm_threshold):
    if not 0 <= top_percent <= 100:
        raise ValueError("--top must be between 0 and 100")

    df = pd.read_csv(input_path, sep="\t")
    if df.empty:
        raise ValueError(f"Input TSV is empty: {input_path}")

    # Update headers based on tool used
    if salmon:
        new_headers = ["target_id", "length", "eff_length", "tpm", "est_counts"]
        df.columns = new_headers

    require_columns(df, ["target_id", "tpm"])

    # Choose the best target_id based on the highest tpm
    best_row = df.loc[df["tpm"].idxmax()]
    best_tpm = best_row["tpm"]
    best_target_id = best_row["target_id"]

    # Write the best target id
    with open(best_ref_txt, "w") as f:
        f.write(f"{best_target_id}\n")

    # Extract genotype and subtype
    best_genotype, best_subtype = extract_genotype_subtype(best_target_id)

    # Find the n-best target_ids within top_percent of the highest tpm
    threshold_tpm = best_tpm - (best_tpm * (top_percent / 100))
    close_hits_df = df[df["tpm"] >= threshold_tpm]
    close_hits_list = [x for x in close_hits_df["target_id"].tolist() if x != best_target_id]
    close_hits = ";".join(close_hits_list)

    # Check for conflicting subtypes where TPM >= tpm_threshold
    other_subtypes = []
    for _, row in df.iterrows():
        if row["target_id"] != best_target_id:
            if row["tpm"] >= tpm_threshold:
                genotype, subtype = extract_genotype_subtype(row["target_id"])
                if subtype != best_subtype:
                    other_subtypes.append(row["target_id"])

    # also consider the close_hits from earlier
    for ch in close_hits_list:
        genotype, subtype = extract_genotype_subtype(ch)
        if subtype != best_subtype:
            other_subtypes.append(ch)

    # Preserve input order while removing duplicates.
    other_subtypes = list(dict.fromkeys(other_subtypes))

    if len(other_subtypes) > 0:
        print(
            f"Warning: the main subtype was detected as {best_subtype}, "
            f"but there are potentially other subtypes present: {', '.join(other_subtypes)}",
            file=sys.stderr,
        )

    with open(alternate_subtype_txt, "w") as f:
        # also write in the main subtype to help with read mapping
        f.write(f"{best_target_id}\n")
        for st in other_subtypes:
            f.write(f"{st}\n")

    # Write out the TSV file
    with open(output_path, "w") as f:
        f.write("sample_id\tgenotype\tsubtype\tbest_ref\tclose_hits\tother_potential_subtypes\n")
        f.write(
            f'{sample_name}\t{best_genotype}\t{best_subtype}\t{best_target_id}\t{close_hits}\t{";".join(other_subtypes)}\n'
        )

def extract_genotype_subtype(target_id):
    parts = target_id.split("_")
    if not parts or not parts[0]:
        raise ValueError(f"Unable to parse genotype/subtype from target ID: {target_id}")

    subtype = parts[0]
    genotype = "".join([char for char in subtype if char.isdigit()])
    return genotype, subtype

if __name__ == "__main__":
    args = parse_args()
    try:
        process_data(
            args.input,
            args.salmon,
            args.sample_name,
            args.top,
            args.best_ref_txt,
            args.alternate_subtype_txt,
            args.output,
            args.tpm_threshold,
        )
    except ValueError as exc:
        print(str(exc), file=sys.stderr)
        sys.exit(1)
